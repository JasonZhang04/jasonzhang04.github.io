export type IconName = keyof typeof ICONS;

export function PixelIcon({ name, className }: { name: IconName; className?: string }) {
  const rows = ICONS[name];
  const w = rows[0].length;
  const h = rows.length;
  let d = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < w) {
      if (row[x] !== '#') { x++; continue; }
      let run = 1;
      while (x + run < w && row[x + run] === '#') run++;
      d += `M${x} ${y}h${run}v1h-${run}z`;
      x += run;
    }
  });
  return (
    <svg
      className={`pixel-icon${className ? ` ${className}` : ''}`}
      viewBox={`0 0 ${w} ${h}`}
      style={{ '--icon-w': w, '--icon-h': h } as React.CSSProperties}
      shapeRendering="crispEdges"
      fill="currentColor"
      aria-hidden="true"
      focusable="false"
    >
      <path d={d} />
    </svg>
  );
}
